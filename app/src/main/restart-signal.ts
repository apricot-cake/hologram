'use strict';

// restart-app.ps1 が稼働中のアプリを止めるために使う取り決め。「外から正しい
// electron.exe を見つけて kill する」を置き換えるもの。
//
// 旧来のやり方をなぜ正しくできなかったか: あるインスタンスを「本物のアプリ」に
// しているのは、それが開いた設定ディレクトリ（userData）——本物は
// %APPDATA%\Hologram を持ち、サンドボックス／テストのインスタンスはすべて
// HOLOGRAM_CONFIG_DIR で別の場所に固定されている。この属性はプロセスの内側に
// あり、外からは何も読めない。だからスクリプトがこれまで使ってきたフィルタは
// すべてその代わり（proxy）にすぎず、それぞれ片側で失敗していた: '*hologram*'
// というパスの部分文字列は worktree のテストインスタンスまで巻き込んでいた
// （2026-08-05）。--remote-debugging-port の印は、それ無しで起動されたインスタンスを
// 見逃していた（#1004）。exe の正確なパスでさえ、同じツリーから起動された
// サンドボックスと本物を区別できない——それらは同一のバイナリを実行し、環境
// だけが違う（scripts/sandbox-app.cts は同じ lib-electron-path.cts 経由で
// electron を解決する）。
//
// Electron の単一インスタンスロックは、まさに欲しい属性（アプリ名 + userData）を
// キーにしていて、ロックを取れなかった起動は、終了する前に自分の argv を
// ロック保持者へ渡す。だから QUIT_FLAG を持つ使い捨ての起動は、本物の
// インスタンスにだけ届く: OS が正しいキーで識別を行い、代理は要らない。
// サンドボックスは別のロックを持っていて、それを一切耳にしない。
//
// この終了コードは、同じ使い捨ての起動を、スクリプトがポーリングできる
// プローブに変える。新しいインスタンスを起動する前に、古いインスタンスが
// 本当にいなくなったことを知る必要があり（早すぎると新しい起動がロックを
// 取れずに死ぬ）、それを知るために Windows にプロセス一覧を尋ねれば、
// 当て推量がそのまま戻ってくることになる。

const QUIT_FLAG = '--hologram-quit';

// QUIT_FLAG を持つ起動の終了コード。読むのは restart-app.ps1 だけだが、それでも
// このフラグの隣に置いてある: それはプロセス境界の向こう側にあって数字を
// ハードコードしているので、両者を同期させておく import は存在しない——
// このコメントとテストだけが頼り。
const EXIT_NO_INSTANCE = 0; // 誰もロックを持っていなかった——何も動いていなかった
const EXIT_SIGNALLED = 3; // インスタンスがロックを持っていて、終了するよう伝えた

function hasQuitSignal(argv: string[]): boolean {
  return argv.includes(QUIT_FLAG);
}

export { EXIT_NO_INSTANCE, EXIT_SIGNALLED, QUIT_FLAG, hasQuitSignal };
